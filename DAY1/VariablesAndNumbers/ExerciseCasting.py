x = 'hello'
print(x)

y = int(4.5)
z = str(4.5)
print(y)  # Output: 4 (int) 
print(z)  # Output: '4.5' (str)
print('type of y is ', type(y))  # Output: <class 'int'>
print('type of z is ', type(z))  # Output: <class 'str'>


var = float(y)
print(var)  # Output: 4.0 (float)
print('type of var is ', type(var))  # Output: <class 'float'>